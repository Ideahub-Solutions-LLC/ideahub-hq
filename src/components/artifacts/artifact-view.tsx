import Link from "next/link";
import type { Artifact } from "@/db/schema";
import type { DraftActionList } from "@/lib/workflows/meeting-actions";
import type { DraftStatusSummary, SummaryLine } from "@/lib/workflows/weekly-summary";
import { Badge, AiBadge } from "@/components/ui/badge";
import { Notice } from "@/components/ui/card";
import { fmtDate } from "@/lib/format";

/** Renders an artifact so a reviewer can understand it without reading any chat. */
export function ArtifactView({ artifact }: { artifact: Artifact }) {
  if (artifact.kind === "draft_action_list") return <ActionListView draft={artifact.content as unknown as DraftActionList} />;
  if (artifact.kind === "draft_status_summary") return <StatusSummaryView summary={artifact.content as unknown as DraftStatusSummary} />;
  return <pre className="overflow-x-auto rounded-xl bg-surface-2 p-3 text-xs">{JSON.stringify(artifact.content, null, 2)}</pre>;
}

export function ArtifactStatusBadge({ status }: { status: Artifact["status"] }) {
  return <Badge tone={status === "reviewed" ? "emerald" : status === "rejected" ? "rose" : status === "superseded" ? "neutral" : "amber"}>{status === "draft" ? "Draft — awaiting human review" : status}</Badge>;
}

function ActionListView({ draft }: { draft: DraftActionList }) {
  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center gap-2 text-xs text-ink-2">
        <AiBadge>AI draft</AiBadge>
        <span>Source: <Link href={`/knowledge/${draft.sourceId}`} className="text-accent hover:underline">{draft.sourceTitle}</Link></span>
        <span>· Generated by {draft.generatedBy}</span>
      </div>
      <div className="grid grid-cols-2 gap-2 sm:grid-cols-5">
        <MiniStat label="Action items" value={draft.stats.items} />
        <MiniStat label="Owner missing" value={draft.stats.missingOwners} tone={draft.stats.missingOwners ? "rose" : undefined} />
        <MiniStat label="Owner unverified" value={draft.stats.unverifiedOwners} tone={draft.stats.unverifiedOwners ? "amber" : undefined} />
        <MiniStat label="No due date" value={draft.stats.missingDueDates} tone={draft.stats.missingDueDates ? "amber" : undefined} />
        <MiniStat label="Decisions / questions" value={`${draft.stats.decisions} / ${draft.stats.openQuestions}`} />
      </div>
      {draft.notes.length > 0 && (
        <Notice tone="amber" title="Needs human attention">
          <ul className="list-disc pl-4">{draft.notes.map((n, i) => <li key={i}>{n}</li>)}</ul>
        </Notice>
      )}
      <div className="overflow-x-auto rounded-xl border border-line">
        <table className="table">
          <thead><tr><th>#</th><th>Action item</th><th>Proposed owner</th><th>Due</th><th>Source</th></tr></thead>
          <tbody>
            {draft.items.map((it, i) => (
              <tr key={it.id}>
                <td className="text-ink-3">{i + 1}</td>
                <td>
                  <div className="font-medium text-ink">{it.title}</div>
                  {it.flags.includes("excerpt_not_in_source") && <div className="text-xs text-rose">Excerpt not found in source — verify.</div>}
                </td>
                <td>
                  {it.ownerStatus === "identified" && <Badge tone="emerald">{it.proposedOwner}</Badge>}
                  {it.ownerStatus === "unverified" && <div><Badge tone="amber">Unverified: {it.proposedOwner}</Badge><div className="mt-1 text-xs text-ink-2">{it.ownerNote}</div></div>}
                  {it.ownerStatus === "missing" && <div><Badge tone="rose">Owner missing</Badge><div className="mt-1 text-xs text-ink-2">{it.ownerNote}</div></div>}
                </td>
                <td>
                  {it.dueStatus === "stated" && <span className="text-ink">{it.dueText}</span>}
                  {it.dueStatus === "relative" && <span className="text-amber" title="Relative date as written — not converted">“{it.dueText}”</span>}
                  {it.dueStatus === "missing" && <span className="text-ink-3">not stated</span>}
                </td>
                <td className="max-w-xs text-xs text-ink-2">
                  <span className="text-ink-3">line {it.sourceLine}:</span> “{it.sourceExcerpt}”
                </td>
              </tr>
            ))}
            {draft.items.length === 0 && <tr><td colSpan={5} className="text-center text-ink-3">No action items detected.</td></tr>}
          </tbody>
        </table>
      </div>
      <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
        <Sourced title="Decisions recorded" items={draft.decisions} empty="No explicit decisions found." />
        <Sourced title="Open questions" items={draft.openQuestions} empty="No open questions found." />
      </div>
      <p className="text-xs text-ink-3">{draft.disclaimer}</p>
    </div>
  );
}

function Sourced({ title, items, empty }: { title: string; items: { text: string; sourceLine: number; sourceExcerpt: string }[]; empty: string }) {
  return (
    <div className="rounded-xl border border-line p-3">
      <div className="text-xs font-medium uppercase tracking-wider text-ink-3">{title}</div>
      {items.length === 0 ? <p className="mt-1 text-sm text-ink-3">{empty}</p> : (
        <ul className="mt-1.5 space-y-1.5 text-sm">
          {items.map((d, i) => (
            <li key={i}>{d.text} <span className="text-xs text-ink-3">(line {d.sourceLine})</span></li>
          ))}
        </ul>
      )}
    </div>
  );
}

function StatusSummaryView({ summary }: { summary: DraftStatusSummary }) {
  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center gap-2 text-xs text-ink-2">
        <AiBadge>AI draft</AiBadge>
        <span>Period {fmtDate(summary.period.start)} → {fmtDate(summary.period.end)}</span>
        <span>· {summary.stats.recordsScanned} records scanned · generated by {summary.generatedBy}</span>
      </div>
      <p className="text-base font-semibold text-ink">{summary.headline}</p>
      <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
        <Section title="Completed" lines={summary.completed} tone="emerald" />
        <Section title="In progress" lines={summary.inProgress} tone="blue" />
        <Section title="Blockers" lines={summary.blockers} tone="rose" />
        <Section title="Decisions needed" lines={summary.decisionsNeeded} tone="amber" />
        {summary.paused.length > 0 && <Section title="Paused" lines={summary.paused} tone="neutral" />}
      </div>
      {summary.notes.length > 0 && <ul className="list-disc pl-5 text-xs text-ink-2">{summary.notes.map((n, i) => <li key={i}>{n}</li>)}</ul>}
      <p className="text-xs text-ink-3">{summary.disclaimer}</p>
    </div>
  );
}

function Section({ title, lines, tone }: { title: string; lines: SummaryLine[]; tone: "emerald" | "blue" | "rose" | "amber" | "neutral" }) {
  return (
    <div className="rounded-xl border border-line p-3">
      <div className="flex items-center gap-2"><Badge tone={tone}>{title}</Badge><span className="text-xs text-ink-3">{lines.length}</span></div>
      {lines.length === 0 ? <p className="mt-2 text-sm text-ink-3">None recorded.</p> : (
        <ul className="mt-2 space-y-1.5 text-sm">
          {lines.map((l, i) => (
            <li key={i}>
              {l.text}
              {l.owner && <span className="text-ink-3"> · {l.owner}</span>}{" "}
              {l.taskId ? <Link href={`/tasks/${l.taskId}`} className="text-xs text-accent hover:underline">{l.evidence}</Link> : <code className="kbd">{l.evidence}</code>}
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

function MiniStat({ label, value, tone }: { label: string; value: number | string; tone?: "rose" | "amber" }) {
  return (
    <div className="rounded-xl bg-surface-2 px-3 py-2">
      <div className="text-[11px] uppercase tracking-wider text-ink-3">{label}</div>
      <div className={`text-lg font-semibold tabular-nums ${tone === "rose" ? "text-rose" : tone === "amber" ? "text-amber" : "text-ink"}`}>{value}</div>
    </div>
  );
}
